#!/usr/bin/env bash
# Delete sessions whose last update is older than DAYS (default 4) from opencode.db, in short batches.
#
# Safe against a live service: each batch is one small IMMEDIATE transaction (default 100 sessions), the
# connection waits up to 30 s for the write lock, and nothing holds a lock between batches. Foreign keys are
# switched on so session_message, session_part, session_inbox, instruction_* and blob_ref rows cascade.
# event_sequence has no FK to session_v2, so it is pruned by hand in the same transaction.
# Old sessions that are the parent or fork source of a kept session stay, so no kept session dangles.
#
#   DRY=1 scripts/perf/prune-sessions.sh        count only
#   DAYS=4 BATCH=100 scripts/perf/prune-sessions.sh
#
# The file does not shrink: freed pages are reused by later writes. Returning the space to the filesystem needs
# VACUUM, which blocks writers for its whole run, so it is a separate, deliberate step.
set -euo pipefail

DB="${OPENCODE_DB:-$HOME/.local/share/opencode/opencode.db}"
DAYS="${DAYS:-4}"
BATCH="${BATCH:-100}"
CUTOFF=$((($(date +%s) - DAYS * 86400) * 1000))

sql() { sqlite3 -cmd ".timeout 30000" -cmd "PRAGMA foreign_keys=ON" "$DB" "$@"; }

candidates="
  select id from session_v2
  where time_updated < $CUTOFF
    and id not in (select parent_id from session_v2 where parent_id is not null and time_updated >= $CUTOFF)
    and id not in (select fork_session_id from session_v2 where fork_session_id is not null and time_updated >= $CUTOFF)"

total=$(sql "select count(*) from ($candidates)")
kept=$(sql "select count(*) from session_v2")
echo "cutoff_ms=$CUTOFF days=$DAYS sessions=$kept to_delete=$total"
[ "${DRY:-0}" = 1 ] && exit 0

done_count=0
while :; do
  ids=$(sql "$candidates order by time_updated limit $BATCH")
  [ -z "$ids" ] && break
  # Ids are generated by the app; refuse anything that is not a plain token before it reaches SQL.
  if printf '%s\n' "$ids" | grep -qvE '^[A-Za-z0-9_]+$'; then
    echo "unexpected session id shape, aborting" >&2
    exit 1
  fi
  list=$(printf '%s\n' "$ids" | sed "s/.*/'&'/" | paste -sd, -)
  sql "BEGIN IMMEDIATE;
       DELETE FROM session_v2 WHERE id IN ($list);
       DELETE FROM event_sequence WHERE aggregate_id IN ($list);
       COMMIT;"
  done_count=$((done_count + $(printf '%s\n' "$ids" | wc -l)))
  echo "deleted=$done_count/$total"
done
echo "PRUNE-DONE deleted=$done_count"
